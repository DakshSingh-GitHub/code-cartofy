import { NextResponse } from "next/server";

interface AnalyzeSpofRequest {
  nodeId: string;
  label: string;
  dependentCount: number;
  dependents?: string[];
  code?: string;
  repoName?: string;
}

export async function POST(request: Request) {
  try {
    const body: AnalyzeSpofRequest = await request.json();
    const { nodeId, label, dependentCount, dependents = [], code = "", repoName = "Repository" } = body;

    const apiKey = process.env.GEMINI_API_KEY?.trim();

    if (!apiKey) {
      return NextResponse.json(
        {
          error: "Gemini API Key is not configured on the server. Please set GEMINI_API_KEY in .env.local.",
          missingKey: true,
        },
        { status: 500 }
      );
    }

    const prompt = `You are a Principal Software Architect analyzing an Architectural Single Point of Failure (SPOF) / "God Module" in a codebase.

CONTEXT:
- File / Module: ${label} (${nodeId})
- Inbound Dependents (Fan-In): ${dependentCount} downstream modules depend on this file.
- Repository: ${repoName}
- Downstream Dependent Files:
${dependents.slice(0, 20).map((d) => `  - ${d}`).join("\n")}${dependents.length > 20 ? `\n  - ...and ${dependents.length - 20} more files` : ""}

SOURCE CODE OF THE MODULE (truncated if large):
\`\`\`typescript
${code.slice(0, 12000)}
\`\`\`

YOUR TASK:
1. Diagnose why this file became a single point of failure and what risks this high fan-in creates (tight coupling, breaking blast radius, race conditions, testing difficulty).
2. Recommend a concrete architectural design pattern to decouple it (e.g., Facade Pattern, Dependency Inversion, Micro-Utilities, Segregated Interfaces, Event-Driven Bus).
3. Provide an actionable step-by-step refactoring plan.
4. Suggest 2-3 decoupled modular files to extract out of this God file, with realistic TypeScript/JavaScript code snippets.
5. Generate a comprehensive, professional GitHub Issue (Title, Markdown Body, and Labels) ready to be submitted to the scanned GitHub repository to track this architectural improvement.

IMPORTANT: Your response MUST be valid JSON matching this schema:
{
  "summary": "Concise 2-3 sentence overview of why this file is a high-risk bottleneck.",
  "riskLevel": "Critical" | "High" | "Medium",
  "architecturalPattern": "Name of the recommended architectural pattern (e.g. Facade Pattern)",
  "blastRadiusDescription": "Explanation of the blast radius and cascading failure risks.",
  "refactoringPlan": [
    "Step 1: ...",
    "Step 2: ...",
    "Step 3: ...",
    "Step 4: ..."
  ],
  "proposedModules": [
    {
      "path": "suggested/filepath/here.ts",
      "description": "What this extracted file handles",
      "codeSnippet": "TypeScript code snippet showcasing the extracted logic..."
    }
  ],
  "githubIssue": {
    "title": "[CodeCartofy Architecture] Decouple Single Point of Failure: ${label}",
    "body": "Full GitHub Markdown containing problem statement, blast radius, proposed architecture with code blocks, and checklist.",
    "labels": ["architecture", "refactoring", "tech-debt", "codecartofy"]
  }
}

Respond ONLY with the JSON object. Do not wrap in markdown quotes or preamble.`;

    // Try gemini-2.5-flash first, fallback to gemini-1.5-flash if needed
    const modelsToTry = ["gemini-2.5-flash", "gemini-2.0-flash", "gemini-1.5-flash"];
    let lastError: Error | null = null;
    let responseData: Record<string, unknown> | null = null;

    for (const model of modelsToTry) {
      try {
        const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
        const res = await fetch(geminiUrl, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [
              {
                parts: [{ text: prompt }],
              },
            ],
            generationConfig: {
              temperature: 0.2,
              responseMimeType: "application/json",
            },
          }),
        });

        if (!res.ok) {
          const errBody = await res.json().catch(() => ({}));
          const errMsg = errBody?.error?.message || `HTTP ${res.status}: ${res.statusText}`;
          lastError = new Error(`Gemini API [${model}]: ${errMsg}`);
          // If model doesn't exist, try next model
          if (res.status === 404 || errMsg.toLowerCase().includes("not found")) {
            continue;
          }
          throw lastError;
        }

        const data = await res.json();
        const candidateText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
        if (!candidateText) {
          throw new Error("No response generated by Gemini.");
        }

        // Clean potential markdown fences if present
        let cleanText = candidateText.trim();
        if (cleanText.startsWith("```json")) {
          cleanText = cleanText.replace(/^```json\s*/, "").replace(/```$/, "").trim();
        } else if (cleanText.startsWith("```")) {
          cleanText = cleanText.replace(/^```\s*/, "").replace(/```$/, "").trim();
        }

        responseData = JSON.parse(cleanText) as Record<string, unknown>;
        break; // Successfully obtained and parsed response
      } catch (err: unknown) {
        lastError = err instanceof Error ? err : new Error(String(err));
      }
    }

    if (!responseData) {
      return NextResponse.json(
        {
          error: lastError?.message || "Failed to analyze single point of failure with Gemini API.",
        },
        { status: 500 }
      );
    }

    return NextResponse.json({
      success: true,
      analysis: responseData,
    });
  } catch (error: unknown) {
    console.error("AI SPOF Analysis error:", error);
    const msg = error instanceof Error ? error.message : "Internal server error during SPOF analysis.";
    return NextResponse.json(
      {
        error: msg,
      },
      { status: 500 }
    );
  }
}
